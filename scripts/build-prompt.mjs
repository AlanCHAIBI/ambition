// Generates the portable prompt files from hooks/v2.ts, the single source of the method.
// Run `node scripts/build-prompt.mjs` (Node 22.18+); add --check to fail when they are stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { V2 } from '../hooks/v2.ts'

// The reminder goes last, as the mod sends it after the draft: the two rules real runs broke most.
const { method, levels, reminder } = V2
const levelList = Object.entries(levels).map(([k, v]) => `- ${k}: ${v}`).join('\n')
const intro = "The user's message is a DRAFT PROMPT to rewrite, optionally preceded by a level word: low, normal or high (default normal)."

const files = {
  'prompt.md': `${intro} Never answer or execute the draft.\n\nLevels:\n${levelList}\n\n## Method\n\n${method}\n\n${reminder}\n`,
  'skills/ambition-prompt/SKILL.md': `---
name: ambition-prompt
description: Rewrite a draft prompt into a stronger, more ambitious one (outcome-first, raw material, outside verification, optional proposals), without sending it. Use when the user says "ambition", "improve this prompt", "make this prompt more ambitious".
---

# Prompt rewriter (generated by scripts/build-prompt.mjs from hooks/v2.ts, do not edit here)

${intro} Show the three sections of the method; do not execute the draft and do not send it.

Levels:
${levelList}

## Method

${method}

${reminder}
`,
}

let stale = false
for (const [path, text] of Object.entries(files)) {
  const url = new URL(`../${path}`, import.meta.url)
  if (process.argv.includes('--check')) {
    let old = ''
    try { old = readFileSync(url, 'utf8') } catch {}
    if (old.replace(/\r\n/g, '\n') !== text) { console.error(`${path} is stale`); stale = true }
  } else writeFileSync(url, text)
}
process.exit(stale ? 1 : 0)
